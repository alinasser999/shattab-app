export type MessageKey = keyof typeof messages.en;
export type MessageParams = Record<string, string | number>;

export function t(locale: AdminLocale, key: MessageKey, params?: MessageParams): string {
  const template = messages[locale][key] as string;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name: string) => {
    const value = params?.[name];
    return value === undefined ? match : String(value);
  });
}

export const OUTCOME_KEYS = {
  done: [
    'user_suspended', 'user_unsuspended', 'verified', 'unverified', 'plan_pro', 'plan_free',
    'verification_approved', 'verification_rejected', 'payment_approved', 'payment_rejected',
    'report_dismissed', 'content_removed', 'content_removed_suspended', 'post_removed',
  ],
  error: [
    'session_expired', 'not_authorized', 'not_allowed', 'cannot_suspend_admin', 'already_approved',
    'already_rejected', 'not_found', 'reason_required', 'reason_too_long', 'invalid_plan_days',
    'unsupported_report_target', 'billing_guard', 'generic', 'invalid_id', 'reason_length',
    'give_suspend_reason', 'invalid_plan', 'days_range', 'give_verification_reason',
    'give_payment_reason', 'unknown_moderation', 'give_decision_note', 'give_post_reason',
  ],
} as const;

export type DoneCode = (typeof OUTCOME_KEYS.done)[number];
export type ErrorCode = (typeof OUTCOME_KEYS.error)[number];

export function outcomeKey(kind: 'done' | 'error', code: string): MessageKey {
  const valid = (OUTCOME_KEYS[kind] as readonly string[]).includes(code);
  if (!valid) return kind === 'done' ? 'action.done.generic' : 'action.error.generic';
  return `action.${kind}.${code}` as MessageKey;
}
